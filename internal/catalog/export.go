package catalog

import (
	"bytes"
	"encoding/json"
	"fmt"
	"sort"
	"strings"
)

type exportOp struct {
	Name         string          `json:"name"`
	Version      int             `json:"version"`
	Description  string          `json:"description"`
	MinTier      string          `json:"min_tier"`
	Params       json.RawMessage `json:"params"`
	DryRun       bool            `json:"dry_run"`
	Rollback     *string         `json:"rollback"`
	Irreversible bool            `json:"irreversible"`
	HealthCheck  string          `json:"health_check"`
	FilesWritten []string        `json:"files_written"`
}

type exportDoc struct {
	CatalogVersion string     `json:"catalog_version"`
	Operations     []exportOp `json:"operations"`
}

// Export renders the hub-facing catalog: no argument lists or sudo rules.
func (c *Catalog) Export(catalogVersion string) ([]byte, error) {
	doc := exportDoc{CatalogVersion: catalogVersion, Operations: []exportOp{}}
	for _, d := range c.Definitions() {
		op := exportOp{
			Name: d.Name, Version: d.Version, Description: d.Description,
			MinTier: d.MinTier.String(), Params: d.ParamsRaw, DryRun: len(d.DryRunArgv) > 0,
			Irreversible: d.Irreversible, HealthCheck: d.HealthCheck, FilesWritten: d.FilesWritten,
		}
		if d.Rollback != "" {
			rb := d.Rollback
			op.Rollback = &rb
		}
		doc.Operations = append(doc.Operations, op)
	}
	var buf bytes.Buffer
	enc := json.NewEncoder(&buf)
	enc.SetEscapeHTML(false)
	enc.SetIndent("", "  ")
	if err := enc.Encode(doc); err != nil {
		return nil, err
	}
	return buf.Bytes(), nil
}

// sudoersEscape escapes the characters sudoers treats specially in command
// arguments.
func sudoersEscape(rule string) string {
	r := strings.NewReplacer(`\`, `\\`, `,`, `\,`, `:`, `\:`, `=`, `\=`)
	return r.Replace(rule)
}

// Sudoers renders a sudoers drop-in allowing user to run exactly the
// privileged operation commands. Rules identical for every package manager
// are listed once.
func (c *Catalog) Sudoers(user string) string {
	type rule struct{ ops []string }
	common := map[string]*rule{}
	perPM := map[string]map[string]*rule{}
	envKeep := map[string]bool{}
	add := func(m map[string]*rule, cmd, op string) {
		if m[cmd] == nil {
			m[cmd] = &rule{}
		}
		m[cmd].ops = append(m[cmd].ops, op)
	}
	for _, d := range c.Definitions() {
		if !d.Privileged {
			continue
		}
		same := true
		for _, pm := range PackageManagers {
			same = same && d.Sudo[pm] == d.Sudo[PackageManagers[0]]
			for k := range d.Env[pm] {
				envKeep[k] = true
			}
		}
		if same {
			add(common, d.Sudo[PackageManagers[0]], d.Key())
			continue
		}
		for _, pm := range PackageManagers {
			if perPM[pm] == nil {
				perPM[pm] = map[string]*rule{}
			}
			add(perPM[pm], d.Sudo[pm], d.Key())
		}
	}

	var b strings.Builder
	b.WriteString("# Sudo rules for the Bifrost agent, generated by `bifrost-agent operations sudoers`.\n")
	b.WriteString("# Install as /etc/sudoers.d/bifrost-agent (mode 0440, owner root) and check it with\n")
	b.WriteString("# `visudo -cf /etc/sudoers.d/bifrost-agent`. Keep only the section for this server's\n")
	b.WriteString("# package manager if you like.\n#\n")
	b.WriteString("# A sudoers \"*\" matches any arguments, spaces included. The agent only ever fills\n")
	b.WriteString("# it with one schema-checked argument, but anyone who controls the agent's user can\n")
	b.WriteString("# run these commands with other arguments: protect that user like root.\n")
	if len(envKeep) > 0 {
		keys := sortedKeys(envKeep)
		fmt.Fprintf(&b, "\nDefaults:%s env_keep += \"%s\"\n", user, strings.Join(keys, " "))
	}
	writeRules := func(title string, m map[string]*rule) {
		if len(m) == 0 {
			return
		}
		fmt.Fprintf(&b, "\n# %s\n", title)
		cmds := make([]string, 0, len(m))
		for cmd := range m {
			cmds = append(cmds, cmd)
		}
		sort.Strings(cmds)
		for _, cmd := range cmds {
			fmt.Fprintf(&b, "# %s\n%s ALL=(root) NOPASSWD: %s\n", strings.Join(m[cmd].ops, ", "), user, sudoersEscape(cmd))
		}
	}
	writeRules("Every package manager", common)
	writeRules("apt (Debian, Ubuntu)", perPM[PackageManagerApt])
	writeRules("dnf (RHEL family)", perPM[PackageManagerDnf])
	return b.String()
}

func sortedKeys(m map[string]bool) []string {
	out := make([]string, 0, len(m))
	for k := range m {
		out = append(out, k)
	}
	sort.Strings(out)
	return out
}
